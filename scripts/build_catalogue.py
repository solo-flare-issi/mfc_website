def cell_to_text(value) -> str:
    """Normalise an openpyxl cell value to a clean string."""
    if value is None:
        return ""
    if isinstance(value, dt.datetime):
        return value.strftime("%Y-%m-%d")
    if isinstance(value, dt.time):
        return value.strftime("%H:%M")
    if isinstance(value, float) and value.is_integer():
        return str(int(value))
    return str(value).strip()


def split_multi(value, sep_comma: bool = True) -> list[str]:
    """Split a multi-value cell into one entry per flare.

    Flare information is stored as parallel lists in three adjacent cells
    (time, class, observed-by), one line per flare.  The observed-by cell
    uses commas *within* a line to list several instruments for one flare
    ("EUI, SPICE"), so it must be split on newlines only.
    """
    text = cell_to_text(value)
    if not text or text.lower() in {"none", "n/a", "-"}:
        return []
    parts = re.split(r"[\n,]+" if sep_comma else r"\n+", text)
    return [p.strip() for p in parts if p.strip()]


def roll_date(date: str, time_ut: str, window: str) -> str:
    """Advance the date by a day for flares after a window's midnight rollover.

    A window written "22:30 - 02:30" runs past midnight; a flare at 01:48
    inside it belongs to the following day.
    """
    m = re.match(r"\s*(\d{1,2})[:.](\d{2})", window or "")
    t = re.match(r"(\d{1,2}):(\d{2})", time_ut or "")
    if not m or not t:
        return date
    start_min = int(m.group(1)) * 60 + int(m.group(2))
    flare_min = int(t.group(1)) * 60 + int(t.group(2))
    if flare_min >= start_min:
        return date
    try:
        d = dt.date.fromisoformat(date)
    except ValueError:
        return date
    return (d + dt.timedelta(days=1)).isoformat()


def parse_flares(uid: str, date: str, times, classes, observers,
                 earth: str, au: str, hgs: str, window: str = "") -> list[Flare]:
    """Zip the three parallel flare cells into Flare records."""
    t_list = split_multi(times)
    c_list = split_multi(classes)
    o_list = split_multi(observers, sep_comma=False)
    if not t_list and not c_list:
        return []

    n = max(len(t_list), len(c_list))
    flares = []
    for i in range(n):
        time_ut = t_list[i] if i < len(t_list) else ""
        goes = c_list[i] if i < len(c_list) else ""
        obs = o_list[i] if i < len(o_list) else (o_list[0] if len(o_list) == 1 else "")
        if not time_ut and not goes:
            continue
        # normalise HH:MM
        m = re.match(r"(\d{1,2})[:.](\d{2})", time_ut)
        time_ut = f"{int(m.group(1)):02d}:{m.group(2)}" if m else time_ut
        fdate = roll_date(date, time_ut, window)
        slug = f"{fdate}T{time_ut.replace(':', '-')}" if time_ut else f"{fdate}-{i + 1}"
        flares.append(Flare(
            flare_id=slug, campaign_uid=uid, date=fdate, time_ut=time_ut,
            goes_class=goes, observed_by=obs, seen_from_earth=earth,
            so_au=au, hg_stonyhurst=hgs,
        ))
    return flares


def season_for(ltp: str, date: str) -> str:
    """Derive a season label from the LTP, falling back to the date."""
    mapping = {
        "LTP11": "Spring 2023", "LTP15": "Spring 2024", "LTP17": "Autumn 2024",
        "LTP19": "Spring 2025", "LTP21": "Autumn 2025", "LTP22": "Winter 2026",
        "LTP24": "Summer 2026",
    }
    key = ltp.strip().upper().replace(" ", "")
    if key in mapping:
        # the Dec 2024 trigger block sits in LTP17 but reads as Winter 2024
        if key == "LTP17" and date >= "2024-11-01":
            return "Winter 2024"
        if key == "LTP21" and date >= "2025-11-01":
            return "Winter 2025"
        return mapping[key]
    return ""


