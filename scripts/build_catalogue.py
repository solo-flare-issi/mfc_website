#!/usr/bin/env python3
"""Generate the campaign and flare catalogue pages from the working spreadsheet.

Reads, in order of preference:
    a published Google Sheet, if MFC_SHEET_URL is set (see below)
    data/Full Major Flare Catalogue.xlsx   the team's working catalogue
    data/mfc_catalogue_final.csv           SOAR-verified observed windows

To build straight from Google Sheets, publish the sheet to the web
(File > Share > Publish to web) and set the sheet key:

    export MFC_SHEET_KEY=1AbC...              # the id from the sheet URL
    python scripts/build_catalogue.py

Each worksheet is then fetched as CSV over the network.  Without that
variable the local spreadsheet in data/ is used, so the build stays
reproducible and works offline.

Writes:
    docs/_data/campaigns.csv               flat campaign table
    docs/_data/flares.csv                  flat flare table
    docs/campaigns/index.md                campaign catalogue page
    docs/campaigns/<uid>.md                one page per campaign
    docs/flares/index.md                   flare catalogue page
    docs/flares/<flare_id>.md              one page per flare

Everything under docs/campaigns/ and docs/flares/ is generated -- do not
edit those files by hand.  Run this after editing the spreadsheet:

    python scripts/build_catalogue.py
"""

