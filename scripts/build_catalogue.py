def html_link(text: str, href: str) -> str:
    return f'<a href="{href}">{text}</a>'


def interactive_table(
    headers: list[str],
    rows: list[list[str]],
    filters: list[tuple[str, int, list[str]]] | None = None,
    numeric_cols: set[int] | None = None,
) -> str:
    """Render a sortable, searchable HTML table with filter dropdowns.

    Enhanced by _static/catalogue.js.  Without JavaScript it degrades to
    a plain HTML table that still reads correctly.
    """
    numeric_cols = numeric_cols or set()
    out = ['<div class="mfc-table-wrapper">', '<div class="mfc-toolbar">']
    out.append(
        '<input type="search" class="mfc-search" '
        'placeholder="Search..." aria-label="Search the table">'
    )
    for label, col, options in (filters or []):
        out.append(f'<select class="mfc-filter" data-column="{col}" aria-label="{label}">')
        out.append(f'<option value="">{label}: all</option>')
        for opt in options:
            out.append(f'<option value="{opt}">{opt}</option>')
        out.append("</select>")
    out.append('<button type="button" class="mfc-reset">Reset</button>')
    out.append("</div>")
    out.append('<p class="mfc-count"></p>')
    out.append('<div class="mfc-scroll"><table class="mfc-table"><thead><tr>')
    for i, h in enumerate(headers):
        num = ' data-numeric="true"' if i in numeric_cols else ""
        out.append(f"<th{num}>{h}</th>")
    out.append("</tr></thead><tbody>")
    for r in rows:
        out.append("<tr>" + "".join(f"<td>{c}</td>" for c in r) + "</tr>")
    out.append("</tbody></table></div>")
    out.append('<p class="mfc-empty" hidden>No rows match those filters.</p>')
    out.append("</div>")
    return "\n".join(out)


def md_table(headers: list[str], rows: list[list[str]]) -> str:
    out = ["| " + " | ".join(headers) + " |",
           "| " + " | ".join("---" for _ in headers) + " |"]
    for r in rows:
        out.append("| " + " | ".join(x if x else "" for x in r) + " |")
    return "\n".join(out)


def write_campaign_page(c: Campaign) -> None:
    L = ["---", "html_theme.sidebar_secondary.remove: true", "---", "",
         GENERATED_NOTE, f"# {c.uid}", ""]
    subtitle = f"{c.type_label}, {c.date}"
    if c.season:
        subtitle += f", {c.season}"
    L.append(f"**{subtitle}**")
    L.append("")

    # quick facts
    facts = [
        ("LTP", c.ltp), ("RSW", c.rsw), ("Season", c.season),
        ("Date", c.date), ("Planned window (UT)", c.window),
        ("Instruments in SOAR", c.instruments_soar),
        ("SOOP", f"`{c.soop}`" if c.soop else ""),
        ("Spacecraft distance", f"{c.so_au} AU" if c.so_au else ""),
        ("Spacecraft location (HG Stonyhurst)", c.so_location),
        ("Target coordinates", c.target_coords),
        ("Viewable from Earth", c.seen_from_earth),
    ]
    if c.trigger_instrument:
        facts.insert(4, ("Triggering instrument", c.trigger_instrument))
    L += ["## Quick facts", "",
          md_table(["Property", "Value"], [[k, v] for k, v in facts if v]), ""]

    # planned vs observed
    per_inst = []
    for name, planned, observed, files, cadence in [
        ("EUI", c.eui_window, c.eui_observed, c.eui_files, c.eui_cadence),
        ("SPICE", c.spice_window, c.spice_observed, c.spice_files, c.spice_cadence),
        ("PHI", c.phi_window, c.phi_observed, c.phi_files, c.phi_cadence),
    ]:
        if planned or observed:
            per_inst.append([name, planned, observed, files, cadence])
    if per_inst:
        L += ["## Planned and observed windows", "",
              "Observed windows, file counts and cadences are as verified "
              "against [SOAR](https://soar.esac.esa.int/soar/).", "",
              md_table(["Instrument", "Planned (UT)", "Observed (UT)",
                        "Files", "Cadence"], per_inst), ""]

    if c.notes:
        L += ["## Observer notes", "", c.notes, ""]

    # flares
    L += ["## Flares observed", ""]
    if c.flares:
        rows = [[f"[{f.time_ut}](../flares/{f.flare_id}.md)", f.goes_class, f.observed_by]
                for f in c.flares]
        L += [md_table(["Time (UT)", "GOES class", "Observed by"], rows), ""]
    else:
        L += ["No flare recorded in this window.", ""]

    # products
    L += [
        "## Quicklook products", "",
        ":::{note}",
        "Per-campaign quicklook products (STIX and HRI timeseries, FSI "
        "field-of-view overlays, orbit plots and JHelioviewer movies) are "
        "being generated and will be linked here.",
        ":::", "",
        "## Data access", "",
        f"- **Solar Orbiter data:** [search SOAR for {c.date}]"
        f"(https://soar.esac.esa.int/soar/#search)",
        "- **STIX:** [STIX Data Centre](https://datacenter.stix.i4ds.net/)",
        "- **EUI observing log:** [SIDC EUI wiki]"
        "(https://gitlab-as.oma.be/SIDC/SpaceInstruments/eui/-/wikis/home)",
        "",
        "## Coordinated observations", "",
        "See [Finding coordinated observations](../resources.md) for how to "
        "check IRIS, Hinode, radio and ground-based coverage for this window.",
        "",
        "---", "",
        "**Cite this page**", "",
        "```text",
        f"Hayes, L. et al. (2026). Solar Orbiter Major Flare Campaigns: campaign {c.uid}.",
        f"https://solo-flare-issi.github.io/mfc-website/campaigns/{c.uid}.html",
        "```", "",
    ]
    (DOCS / "campaigns" / f"{c.uid}.md").write_text("\n".join(L))


