def write_campaign_index(campaigns: list[Campaign]) -> None:
    rows = []
    for c in campaigns:
        rows.append([
            html_link(c.uid, f"{c.uid}.html"),
            f'<span class="mfc-tag mfc-tag-{"trigger" if c.kind == "Trigger" else "soop"}">'
            f"{c.type_label}</span>",
            c.date, c.season or c.ltp, c.ltp, c.window,
            c.instruments_soar or "", c.flare_summary,
        ])
    n_soop = sum(1 for c in campaigns if c.kind == "Major Flare")
    n_trig = len(campaigns) - n_soop
    n_flares = sum(len(c.flares) for c in campaigns)
    n_with = sum(1 for c in campaigns if c.flares)

    seasons = sorted({c.season for c in campaigns if c.season})
    ltps = sorted({c.ltp for c in campaigns if c.ltp})

    L = ["---", "html_theme.sidebar_secondary.remove: true", "---", "",
         GENERATED_NOTE, "# Campaign catalogue", "",
         f"Every observing window in the Solar Orbiter Major Flare Campaigns: "
         f"**{n_soop} MFC-SOOP instances** and **{n_trig} flare-trigger windows**, "
         f"{n_with} of which recorded a flare.", "",
         "Click a campaign to open its detail page, which gives the planned and "
         "observed windows for each instrument, the flares captured, and where "
         "to find the data. Column headings sort the table.", "",
         "::::{grid} 2 4 4 4",
         ":gutter: 2", "",
         f":::{{grid-item-card}} {len(campaigns)}",
         ":class-card: mfc-stat", "", "observing windows", ":::", "",
         f":::{{grid-item-card}} {n_soop}",
         ":class-card: mfc-stat", "", "MFC-SOOP instances", ":::", "",
         f":::{{grid-item-card}} {n_trig}",
         ":class-card: mfc-stat", "", "trigger windows", ":::", "",
         f":::{{grid-item-card}} {n_flares}",
         ":class-card: mfc-stat", "", "flares recorded", ":::", "",
         "::::", "",
         interactive_table(
             ["Campaign", "Type", "Date", "Season", "LTP", "Window (UT)",
              "Instruments in SOAR", "Flares"],
             rows,
             filters=[("Type", 1, ["MFC-SOOP", "Trigger"]),
                      ("Season", 3, seasons),
                      ("LTP", 4, ltps)],
         ), "",
         "Prefer a narrative view? [Instances](../instances.md) walks through the "
         "MFC-SOOP campaigns season by season, and "
         "[Trigger Campaigns](../trigger-campaigns.md) covers the EUI and PHI "
         "trigger operations.", "",
         "The same data is available as a CSV download on the "
         "[Data](../data.md) page.", "",
         "```{toctree}", ":hidden:", ":maxdepth: 1", ""]
    L += [c.uid for c in campaigns]
    L += ["```", ""]
    (DOCS / "campaigns" / "index.md").write_text("\n".join(L))


def write_flare_index(campaigns: list[Campaign]) -> None:
    flares = sorted(
        [(f, c) for c in campaigns for f in c.flares], key=lambda p: p[0].sort_key
    )
    rows = [[
        html_link(f"{f.date} {f.time_ut}", f"{f.flare_id}.html"),
        f'<span class="mfc-goes mfc-goes-{f.goes_letter.lower()}">{f.goes_class}</span>',
        f.goes_letter, f.observed_by, f.seen_from_earth,
        f.so_au, html_link(c.uid, f"../campaigns/{c.uid}.html"),
    ] for f, c in flares]

    counts: dict[str, int] = {}
    for f, _ in flares:
        counts[f.goes_letter] = counts.get(f.goes_letter, 0) + 1
    letters = [k for k in ["X", "M", "C", "B", "A"] if k in counts]

    L = ["---", "html_theme.sidebar_secondary.remove: true", "---", "",
         GENERATED_NOTE, "# Flare catalogue", "",
         f"Every flare recorded within a Solar Orbiter Major Flare Campaigns "
         f"window since 2023. Classes for far-side events are estimated from "
         f"STIX. Column headings sort the table.", "",
         "::::{grid} 2 4 4 4", ":gutter: 2", ""]
    L += [f":::{{grid-item-card}} {len(flares)}", ":class-card: mfc-stat", "",
          "flares recorded", ":::", ""]
    for k in letters[:3]:
        L += [f":::{{grid-item-card}} {counts[k]}", ":class-card: mfc-stat", "",
              f"{k}-class", ":::", ""]
    L += ["::::", "",
          ":::{warning} Not yet included",
          "The four flares captured by the PHI trigger campaigns (2024-12-08 "
          "X2.3, 2026-02-03 X1.5, 2026-02-04 X4.2 and 2026-02-06 C2) are "
          "described on the [Trigger Campaigns](../trigger-campaigns.md) page "
          "but have not yet been entered in the working spreadsheet, so they "
          "are absent from the table below.",
          ":::", "",
          interactive_table(
              ["Peak time (UT)", "GOES class", "Class", "Observed by",
               "Seen from Earth", "SO distance (AU)", "Campaign"],
              rows,
              filters=[("Class", 2, letters),
                       ("Seen from Earth", 4, ["Yes", "No"])],
              numeric_cols={5},
          ), "",
          "The same data is available as a CSV download on the "
          "[Data](../data.md) page.", "",
          "```{toctree}", ":hidden:", ":maxdepth: 1", ""]
    L += [f.flare_id for f, _ in flares]
    L += ["```", ""]
    (DOCS / "flares" / "index.md").write_text("\n".join(L))


def write_data_csvs(campaigns: list[Campaign]) -> None:
    out = DOCS / "_data"
    out.mkdir(exist_ok=True)
    camp_fields = [k for k in asdict(campaigns[0]) if k != "flares"]
    with (out / "campaigns.csv").open("w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=camp_fields)
        w.writeheader()
        for c in campaigns:
            d = asdict(c)
            d.pop("flares")
            w.writerow(d)
    flares = [f for c in campaigns for f in c.flares]
    if flares:
        with (out / "flares.csv").open("w", newline="") as fh:
            w = csv.DictWriter(fh, fieldnames=list(asdict(flares[0])))
            w.writeheader()
            for f in flares:
                w.writerow(asdict(f))


