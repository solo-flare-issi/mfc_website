@dataclass
class Flare:
    flare_id: str
    campaign_uid: str
    date: str
    time_ut: str
    goes_class: str
    observed_by: str
    seen_from_earth: str = ""
    so_au: str = ""
    hg_stonyhurst: str = ""

    @property
    def goes_letter(self) -> str:
        m = re.match(r"([A-Z])", self.goes_class.strip().upper())
        return m.group(1) if m else "?"

    @property
    def sort_key(self) -> str:
        return f"{self.date} {self.time_ut}"


@dataclass
class Campaign:
    uid: str
    kind: str            # "Major Flare" or "Trigger"
    ltp: str
    rsw: str
    season: str
    date: str
    window: str
    eui_window: str = ""
    spice_window: str = ""
    phi_window: str = ""
    trigger_instrument: str = ""
    seen_from_earth: str = ""
    so_location: str = ""
    so_au: str = ""
    target_coords: str = ""
    notes: str = ""
    # SOAR verification
    eui_observed: str = ""
    eui_files: str = ""
    eui_cadence: str = ""
    eui_status: str = ""
    spice_observed: str = ""
    spice_files: str = ""
    spice_cadence: str = ""
    phi_observed: str = ""
    phi_files: str = ""
    phi_cadence: str = ""
    instruments_soar: str = ""
    soop: str = ""
    flares: list[Flare] = field(default_factory=list)

    @property
    def type_label(self) -> str:
        if self.kind == "Trigger":
            return f"Trigger ({self.trigger_instrument})" if self.trigger_instrument else "Trigger"
        return "MFC-SOOP"

    @property
    def flare_summary(self) -> str:
        if not self.flares:
            return "none"
        return ", ".join(f.goes_class for f in self.flares)


