SHEET_CSV = ("https://docs.google.com/spreadsheets/d/{key}/gviz/tq"
             "?tqx=out:csv&sheet={sheet}")


def fetch_google_sheet(key: str, sheet: str) -> list[list]:
    """Fetch one worksheet of a published Google Sheet as rows.

    Returns the same shape as openpyxl's iter_rows(values_only=True) so the
    two sources are interchangeable.
    """
    import urllib.parse
    import urllib.request

    url = SHEET_CSV.format(key=key, sheet=urllib.parse.quote(sheet))
    with urllib.request.urlopen(url, timeout=30) as resp:
        text = resp.read().decode("utf-8")
    return [row for row in csv.reader(text.splitlines())]


def read_soar() -> dict[str, dict]:
    if not SOAR_CSV.exists():
        return {}
    with SOAR_CSV.open() as fh:
        return {r["Unique ID"]: r for r in csv.DictReader(fh) if r.get("Unique ID")}


def read_rows(rows: list, kind: str, soar: dict[str, dict]) -> list[Campaign]:
    """Build Campaign records from raw worksheet rows.

    Accepts rows from either openpyxl or a Google Sheets CSV fetch.
    """
    rows = [r for r in rows if any(v not in (None, "") for v in r)]
    campaigns: list[Campaign] = []

    # column layout differs slightly between the two sheets
    if kind == "Trigger":
        C = dict(ltp=0, rsw=1, uid=2, date=3, window=4, trig=5,
                 ftime=6, fclass=7, fobs=8, earth=9, loc=10, au=11,
                 hgs=10, target=12, notes=13)
    else:
        C = dict(ltp=0, rsw=1, uid=2, date=3, window=4, eui=5, spice=6, phi=7,
                 ftime=8, fclass=9, fobs=10, earth=11, loc=12, au=13,
                 hgs=12, target=14, notes=15)

    for row in rows[2:]:
        uid = cell_to_text(row[C["uid"]]) if len(row) > C["uid"] else ""
        if not uid or not re.match(r"^MF[WT]\d{8}", uid):
            continue  # season separator or header repeat

        get = lambda k: cell_to_text(row[C[k]]) if C.get(k) is not None and len(row) > C[k] else ""
        date = get("date")
        ltp = get("ltp")

        c = Campaign(
            uid=uid, kind=kind, ltp=ltp, rsw=get("rsw"),
            season=season_for(ltp, date), date=date, window=get("window"),
            eui_window=get("eui"), spice_window=get("spice"), phi_window=get("phi"),
            trigger_instrument=get("trig"), seen_from_earth=get("earth"),
            so_location=get("loc"), so_au=get("au"), target_coords=get("target"),
            notes=get("notes"),
        )
        c.flares = parse_flares(
            uid, date,
            row[C["ftime"]] if len(row) > C["ftime"] else None,
            row[C["fclass"]] if len(row) > C["fclass"] else None,
            row[C["fobs"]] if len(row) > C["fobs"] else None,
            c.seen_from_earth, c.so_au, c.so_location, c.window,
        )

        if uid in soar:
            s = soar[uid]
            c.eui_observed = s.get("EUI observed (UT)", "")
            c.eui_files = s.get("EUI files", "")
            c.eui_cadence = s.get("EUI cadence", "")
            c.eui_status = s.get("EUI status", "")
            c.spice_observed = s.get("SPICE observed (UT)", "")
            c.spice_files = s.get("SPICE files", "")
            c.spice_cadence = s.get("SPICE cadence", "")
            c.phi_observed = s.get("PHI observed (UT)", "")
            c.phi_files = s.get("PHI files", "")
            c.phi_cadence = s.get("PHI cadence", "")
            c.instruments_soar = s.get("Instruments in SOAR", "")
            c.soop = s.get("EUI SOOP in SOAR", "")
            if not c.season:
                c.season = s.get("Season", "")

        campaigns.append(c)
    return campaigns


